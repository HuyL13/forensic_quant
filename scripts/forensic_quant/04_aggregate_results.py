from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from src.forensic_quant.config import load_config
from src.forensic_quant.results import SummaryInputs, write_summary


def main() -> int:
    parser = argparse.ArgumentParser(description="Aggregate forensic quantization pilot outputs.")
    parser.add_argument("--config", required=True)
    parser.add_argument("--output", default=None)
    args = parser.parse_args()

    config = load_config(args.config)
    output_dir = Path(args.output) if args.output else (config.output_dir or Path("outputs/forensic_quant") / config.run_name)
    output_dir.mkdir(parents=True, exist_ok=True)
    write_summary(
        output_dir / "summary.md",
        SummaryInputs(
            run_name=config.run_name,
            decoder_eval_csv=output_dir / "decoder_eval.csv",
            t2i_eval_csv=output_dir / "t2i_eval.csv",
            residual_alignment_csv=output_dir / "residual_alignment.csv",
            notes=["Generated by scripts/forensic_quant/04_aggregate_results.py"],
        ),
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
